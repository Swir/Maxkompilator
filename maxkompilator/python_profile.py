"""Side-effect-free PyInstaller profile planning for name, icon and Windows version.

Build metadata is generated by a build step, never by project inspection.
The metadata generator executes as plain Python using the selected build
interpreter and therefore works even when Maxkompilator is frozen into an EXE.
"""

from __future__ import annotations

from dataclasses import dataclass, replace
from pathlib import Path
import textwrap

from .app_profile import load_app_profile, native_icon
from .models import BuildStep, PlanError, Project


_WINDOWS_VERSION_RENDER = textwrap.dedent(r'''
    import pathlib
    import sys

    destination = pathlib.Path(sys.argv[1])
    version = sys.argv[2]
    name = sys.argv[3]
    numbers = [int(component) for component in version.split('-', 1)[0].split('.')]
    fixed_version = tuple((numbers + [0, 0, 0, 0])[:4])
    escaped_name = repr(name)
    escaped_version = repr(version)
    escaped_filename = repr(name + '.exe')
    body = f"""VSVersionInfo(
      ffi=FixedFileInfo(filevers={fixed_version!r}, prodvers={fixed_version!r},
        mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0,
        date=(0, 0)),
      kids=[StringFileInfo([StringTable('040904B0', [
        StringStruct('FileDescription', {escaped_name}),
        StringStruct('FileVersion', {escaped_version}),
        StringStruct('InternalName', {escaped_name}),
        StringStruct('OriginalFilename', {escaped_filename}),
        StringStruct('ProductName', {escaped_name}),
        StringStruct('ProductVersion', {escaped_version})
      ])]), VarFileInfo([VarStruct('Translation', [1033, 1200])])]
    )
    """
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(body, encoding='utf-8')
''').strip()


@dataclass(frozen=True)
class PythonProfilePlan:
    project: Project
    steps: tuple[BuildStep, ...]
    pyinstaller_arguments: tuple[str, ...]


def resolve_python_profile(
    project: Project,
    selected_format: str,
    target: str | None,
    output_dir: Path,
    interpreter: str,
) -> PythonProfilePlan:
    """Resolve profile safely without touching the filesystem.

    target may be None for a zipapp (an OS-independent source archive).
    """
    profile = load_app_profile(project.root, project.name)
    if profile.explicit_name:
        project = replace(project, name=profile.name)
    if selected_format == 'zipapp':
        if profile.version is not None or profile.icon is not None:
            raise PlanError('zipapp cannot embed [app].version or [app].icon; choose executable.')
        return PythonProfilePlan(project, (), ())
    if target is None:
        raise PlanError('A native target is required for a PyInstaller profile.')
    icon = native_icon(profile, target)
    args: list[str] = []
    steps: list[BuildStep] = []
    if icon:
        args.extend(('--icon', str(icon)))
    if profile.version:
        if not target.startswith('win-'):
            raise PlanError('PyInstaller native version resource embedding requires a Windows target.')
        # Keep the generated file outside PyInstaller's --clean work directory.
        version_file = output_dir / '.metadata' / 'windows-version.txt'
        steps.append(BuildStep(
            'Generate Windows application version resource',
            (interpreter, '-c', _WINDOWS_VERSION_RENDER,
             str(version_file), profile.version, project.name),
            project.root,
        ))
        args.extend(('--version-file', str(version_file)))
    return PythonProfilePlan(project, tuple(steps), tuple(args))
